// Builds site/map.js: the contiguous United States in a single Albers equal-area conic projection
// (USGS standard parallels 29.5°N and 45.5°N), drawn to scale, plus the six stations.
// Source: US Census Bureau cartographic boundary files, 2017 edition (public domain), via us-atlas 3.0.1 (ISC).
import { readFileSync, writeFileSync } from "node:fs";
import { feature, mesh, merge } from "topojson-client";
import { presimplify, simplify } from "topojson-simplify";
import { geoAlbers, geoPath, geoDistance } from "d3-geo";

// Simplified (audit P12, 19 November 2026): points that change the outline by less than a tiny area are
// dropped, and coordinates are rounded to whole map units (the map is 975 units wide, so a unit is about a
// screen pixel or less). MIN_AREA is in square degrees: 1e-3 gave 37 KB with no visible change at the page's
// sizes (198 KB before; 3e-3 gave 21 KB, slightly smoother). The land is filled from the outline, so the
// states aren't drawn twice.
const MIN_AREA = Number(process.argv[3] || 1e-3);
const us = simplify(presimplify(JSON.parse(readFileSync(new URL("./node_modules/us-atlas/states-10m.json", import.meta.url)))), MIN_AREA);
const OUT = process.argv[2];
const W = 975, H = 610, PAD = 12;
const away = new Set(["02", "15", "60", "66", "69", "72", "78"]); // Alaska, Hawaii, territories
const lower48 = { type: "GeometryCollection", geometries: us.objects.states.geometries.filter((g) => !away.has(g.id)) };
const land = merge(us, lower48.geometries);
const proj = geoAlbers().parallels([29.5, 45.5]).rotate([96, 0]).fitExtent([[PAD, PAD], [W - PAD, H - PAD]], land);
const path = geoPath(proj);
const round = (d) => d.replace(/-?\d+\.\d+/g, (n) => String(Math.round(+n)));
const borders = round(path(mesh(us, lower48, (a, b) => a !== b)));
const outline = round(path(land));

const STATIONS = [
  { name: "Seattle", station: "KSEA", lat: 47.45, lon: -122.31 },
  { name: "Phoenix", station: "KPHX", lat: 33.43, lon: -112.01 },
  { name: "Denver", station: "KDEN", lat: 39.85, lon: -104.66 },
  { name: "Chicago", station: "KORD", lat: 41.98, lon: -87.90 },
  { name: "New York", station: "KNYC", lat: 40.78, lon: -73.97 },
  { name: "Miami", station: "KMIA", lat: 25.79, lon: -80.29 }
].map((s) => { const [x, y] = proj([s.lon, s.lat]); return { ...s, x: +x.toFixed(1), y: +y.toFixed(1) }; });

// Map units per kilometer along 39°N near the center (an equal-area map's scale varies a little with place).
const a = [-99, 39], b = [-93, 39];
const km = geoDistance(a, b) * 6371.0088;
const [ax, ay] = proj(a), [bx, by] = proj(b);
const unitsPerKm = Math.hypot(bx - ax, by - ay) / km;

const js = "// Generated by build.mjs from the US Census Bureau's cartographic boundary files (2017, public domain),\n" +
  "// via us-atlas 3.0.1 (ISC). Contiguous United States, Albers equal-area conic, standard parallels 29.5°N and 45.5°N.\n" +
  "window.TF_MAP = " + JSON.stringify({ width: W, height: H, unitsPerKm: +unitsPerKm.toFixed(5), borders, outline, stations: STATIONS }) + ";\n";
writeFileSync(OUT, js);
console.log("bytes", js.length, "unitsPerKm", unitsPerKm.toFixed(4), "500 km =", (500 * unitsPerKm).toFixed(1), "units");
console.log(STATIONS.map((s) => s.name + " " + s.x + "," + s.y).join(" | "));
